import Foundation

@main
enum SettingsCheck {
    static func main() {
        let suiteName = "local.dither.settings-check.\(UUID().uuidString)"
        let defaults = UserDefaults(suiteName: suiteName)!
        let settings = DitherSettings(defaults: defaults)

        defaults.set(0.765, forKey: "dpr")
        assert(settings.configuration.dpr == 0)
        assert(settings.configuration.pixelSize == 2)
        assert(abs(settings.configuration.waveDirection - 135) < 0.0001)
        assert(abs(DitherConfiguration.waveDirectionVector(for: 135).x - 1) < 0.0001)
        assert(abs(DitherConfiguration.waveDirectionVector(for: 135).y - 1) < 0.0001)
        let up = DitherConfiguration.waveDirectionVector(for: 0)
        let right = DitherConfiguration.waveDirectionVector(for: 90)
        let down = DitherConfiguration.waveDirectionVector(for: 180)
        let left = DitherConfiguration.waveDirectionVector(for: 270)
        assert(abs(up.x) < 0.0001 && up.y < 0)
        assert(right.x > 0 && abs(right.y) < 0.0001)
        assert(abs(down.x) < 0.0001 && down.y > 0)
        assert(left.x < 0 && abs(left.y) < 0.0001)
        assert(settings.configuration.gap == 0)
        assert(settings.configuration.cornerRadius == 0)
        assert(settings.configuration.joinAdjacentSquares == false)
        assert(settings.configuration.ditherStrength == 1)
        defaults.set(true, forKey: "transparent")
        assert(!settings.configuration.transparent)
        assert(String(describing: settings.value(for: "waveSpeed")) == "0.05")
        settings.set(6, for: "ditherMode")
        assert(settings.configuration.ditherMode == 6)
        settings.set("0.25", for: "waveSpeed")
        assert(settings.configuration.waveSpeed == 0.25)
        settings.set("405", for: "waveDirection")
        assert(abs(settings.configuration.waveDirection - 45) < 0.0001)
        settings.set("22", for: "waveDirection")
        assert(abs(settings.configuration.waveDirection - 0) < 0.0001)
        settings.set("360", for: "waveDirection")
        assert(abs(settings.configuration.waveDirection - 0) < 0.0001)
        settings.set("135", for: "waveDirection")
        settings.reload()
        assert(abs(settings.configuration.waveDirection - 135) < 0.0001)
        settings.set("not a number", for: "waveDirection")
        assert(abs(settings.configuration.waveDirection - 135) < 0.0001)
        settings.set("nan", for: "waveDirection")
        assert(abs(settings.configuration.waveDirection - 135) < 0.0001)
        settings.set("not a number", for: "waveSpeed")
        assert(settings.configuration.waveSpeed == 0.25)
        settings.set("0.37", for: "ditherStrength")
        assert(abs(settings.configuration.ditherStrength - 0.37) < 0.0001)
        settings.set("-0.2", for: "waveSpeed")
        settings.set("90", for: "waveDirection")
        let migrated = settings.configuration
        assert(abs(migrated.waveSpeed - 0.2) < 0.0001)
        assert(abs(migrated.waveDirection - 270) < 0.0001)
        assert(abs(((settings.value(for: "waveSpeed") as? NSNumber)?.floatValue ?? 0) - 0.2) < 0.0001)
        assert(abs(((settings.value(for: "waveDirection") as? NSNumber)?.floatValue ?? 0) - 270) < 0.0001)

        settings.set("#FF2600", for: "waveColor")
        settings.set("dim", for: "backgroundStyle")
        let dim = settings.configuration
        assert(abs(dim.backgroundColor.x - dim.waveColor.x * 0.2) < 0.0001)
        settings.set("#46E1FC", for: "waveColor")
        let changed = settings.configuration
        assert(abs(changed.backgroundColor.y - changed.waveColor.y * 0.2) < 0.0001)
        settings.set("white", for: "backgroundStyle")
        assert(settings.configuration.backgroundColor.x == 1)
        settings.set("#000000", for: "waveColor")
        settings.set("black", for: "backgroundStyle")
        assert(settings.configuration.backgroundColor == .zero)
        settings.set("#FF2600, #000000", for: "palette")
        settings.set("#FF2600", for: "waveColor")
        assert(settings.configuration.backgroundColor == .zero)
        settings.set("background", for: "colorPlacement")
        settings.set("black", for: "squareStyle")
        let backgroundMode = settings.configuration
        assert(abs(backgroundMode.backgroundColor.x - 1) < 0.0001)
        assert(abs(backgroundMode.backgroundColor.y - (38.0 / 255.0)) < 0.0001)
        assert(backgroundMode.backgroundColor.z == 0)
        assert(backgroundMode.waveColor == .zero)
        assert(backgroundMode.palette.isEmpty)
        settings.reload()
        assert(abs(settings.configuration.backgroundColor.x - 1) < 0.0001)
        assert(abs(settings.configuration.backgroundColor.y - (38.0 / 255.0)) < 0.0001)
        defaults.removeObject(forKey: "colorPlacement")
        defaults.removeObject(forKey: "squareStyle")
        assert(settings.configuration.backgroundColor == .zero)
        settings.set("0.2", for: "gap")
        settings.set("0.35", for: "cornerRadius")
        assert(settings.configuration.gap == 0.2)
        assert(settings.configuration.cornerRadius == 0.35)
        settings.set(true, for: "joinAdjacentSquares")
        assert(settings.configuration.joinAdjacentSquares)

        defaults.removePersistentDomain(forName: suiteName)
        print("SettingsCheck passed")
    }
}
